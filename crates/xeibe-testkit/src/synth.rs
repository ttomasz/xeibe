//! Synthetic GML datasets of any size, for the benchmarks (`docs/benchmarks.md`).
//!
//! A [`Synth`] describes a GML 3.2 feature collection: how many features, the
//! shape of their geometry and how many properties they carry. The same
//! description always gives the same bytes: coordinates and values come from
//! a seeded generator, not from the clock or the system's randomness, so
//! runs on one machine compare and a regression shows as a regression.
//!
//! The features look like real cadastral or topographic data, as far as a
//! reader's work goes: EPSG:2180 coordinates with two decimals, northing first
//! as the `urn:ogc:def:crs:EPSG::2180` srsName says, identifiers with leading
//! zeros, dates, timestamps, booleans, a repeated element (a list column) and
//! the occasional entity in a string.

use std::fmt::Write;

use crate::gml::{APP, GML_32, XLINK, XSI};

/// The layer every [`Synth`] document holds.
pub const LAYER: &str = "Building";
/// The layer [`Synth::other_layer_every`] interleaves with [`LAYER`].
pub const OTHER_LAYER: &str = "Road";
/// The srsName on every geometry.
pub const SRS_NAME: &str = "urn:ogc:def:crs:EPSG::2180";

/// The geometry of each feature.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum Shape {
    /// `gml:Point` with one `gml:pos`.
    Point,
    /// `gml:LineString` with one `gml:posList` of `vertices` positions.
    LineString { vertices: usize },
    /// `gml:Polygon`: an exterior ring of `vertices` positions (closed, so
    /// one more is written) and `holes` interior rings of 8.
    Polygon { vertices: usize, holes: usize },
    /// `gml:MultiSurface` of `parts` polygons, each like [`Shape::Polygon`]
    /// without holes.
    MultiSurface { parts: usize, vertices: usize },
    /// `gml:Polygon` whose exterior is a `gml:Ring` of one `gml:ArcString`,
    /// a full circle in two arcs: a `CurvePolygon`.
    ArcPolygon,
}

impl Shape {
    /// Positions written per geometry, closing positions included.
    pub fn positions(self) -> usize {
        match self {
            Shape::Point => 1,
            Shape::LineString { vertices } => vertices,
            Shape::Polygon { vertices, holes } => vertices + 1 + holes * 9,
            Shape::MultiSurface { parts, vertices } => parts * (vertices + 1),
            Shape::ArcPolygon => 5,
        }
    }

    /// One geometry element of this shape, with its `srsName`, `gml:id`s
    /// numbered from `seed`.
    pub fn snippet(self, seed: u64) -> String {
        let mut out = String::new();
        let mut rng = Rng::new(seed);
        write_geometry(&mut out, self, &mut rng, seed);
        out
    }
}

/// A GML 3.2 feature collection, generated by [`Synth::document`].
#[derive(Debug, Clone)]
pub struct Synth {
    /// Features of [`LAYER`].
    pub features: usize,
    pub shape: Shape,
    /// String properties `app:attr0`… beyond the fixed set.
    pub extra_properties: usize,
    /// After every this many [`LAYER`] features, one of [`OTHER_LAYER`],
    /// which a read of [`LAYER`] skips in the splitter.
    pub other_layer_every: Option<usize>,
    pub seed: u64,
}

impl Default for Synth {
    /// 1000 points, no extra properties, one layer.
    fn default() -> Self {
        Synth {
            features: 1000,
            shape: Shape::Point,
            extra_properties: 0,
            other_layer_every: None,
            seed: 0x5eed,
        }
    }
}

impl Synth {
    pub fn new(features: usize, shape: Shape) -> Self {
        Synth {
            features,
            shape,
            ..Synth::default()
        }
    }

    /// The whole document.
    pub fn document(&self) -> String {
        let mut rng = Rng::new(self.seed);
        let mut out = String::with_capacity(self.features * (400 + self.shape.positions() * 22));
        write!(
            out,
            "<?xml version=\"1.0\" encoding=\"UTF-8\"?>\n\
             <gml:FeatureCollection xmlns:gml=\"{GML_32}\" xmlns:app=\"{APP}\" \
             xmlns:xlink=\"{XLINK}\" xmlns:xsi=\"{XSI}\" gml:id=\"collection\">\n"
        )
        .unwrap();
        for i in 0..self.features {
            out.push_str("<gml:featureMember>");
            self.write_feature(&mut out, &mut rng, i);
            out.push_str("</gml:featureMember>\n");
            // `Some(0)` never: no number but 0 is a multiple of 0.
            if let Some(every) = self.other_layer_every
                && (i + 1).is_multiple_of(every)
            {
                out.push_str("<gml:featureMember>");
                write_other(&mut out, &mut rng, i);
                out.push_str("</gml:featureMember>\n");
            }
        }
        out.push_str("</gml:FeatureCollection>\n");
        out
    }

    fn write_feature(&self, out: &mut String, rng: &mut Rng, i: usize) {
        write!(out, "<app:{LAYER} gml:id=\"b.{i}\">").unwrap();
        // An entity now and then, so strings aren't all borrowed.
        if i.is_multiple_of(7) {
            write!(out, "<app:name>Smith &amp; Sons {i}</app:name>").unwrap();
        } else {
            write!(out, "<app:name>Building {i}</app:name>").unwrap();
        }
        write!(out, "<app:code>{:08}</app:code>", rng.below(100_000_000)).unwrap();
        write!(out, "<app:floors>{}</app:floors>", 1 + rng.below(12)).unwrap();
        write!(out, "<app:area>{:.2}</app:area>", rng.range(20.0, 5000.0)).unwrap();
        write!(
            out,
            "<app:built>{}-{:02}-{:02}</app:built>",
            1900 + rng.below(125),
            1 + rng.below(12),
            1 + rng.below(28)
        )
        .unwrap();
        write!(
            out,
            "<app:updated>20{:02}-{:02}-{:02}T{:02}:{:02}:{:02}</app:updated>",
            10 + rng.below(16),
            1 + rng.below(12),
            1 + rng.below(28),
            rng.below(24),
            rng.below(60),
            rng.below(60)
        )
        .unwrap();
        write!(out, "<app:active>{}</app:active>", rng.below(2) == 0).unwrap();
        for _ in 0..rng.below(4) {
            write!(out, "<app:tag>t{}</app:tag>", rng.below(50)).unwrap();
        }
        for p in 0..self.extra_properties {
            write!(out, "<app:attr{p}>v{}</app:attr{p}>", rng.below(10_000)).unwrap();
        }
        out.push_str("<app:geometry>");
        write_geometry(out, self.shape, rng, i as u64);
        out.push_str("</app:geometry>");
        write!(out, "</app:{LAYER}>").unwrap();
    }
}

/// A short road: a name and a three-vertex line.
fn write_other(out: &mut String, rng: &mut Rng, i: usize) {
    write!(
        out,
        "<app:{OTHER_LAYER} gml:id=\"r.{i}\"><app:name>Road {i}</app:name><app:geometry>"
    )
    .unwrap();
    write_geometry(out, Shape::LineString { vertices: 3 }, rng, i as u64);
    write!(out, "</app:geometry></app:{OTHER_LAYER}>").unwrap();
}

fn write_geometry(out: &mut String, shape: Shape, rng: &mut Rng, id: u64) {
    // Somewhere in Poland, in PL-1992 metres.
    let e = rng.range(200_000.0, 800_000.0);
    let n = rng.range(150_000.0, 750_000.0);
    match shape {
        Shape::Point => {
            write!(
                out,
                "<gml:Point gml:id=\"g.{id}\" srsName=\"{SRS_NAME}\"><gml:pos>{n:.2} {e:.2}</gml:pos></gml:Point>"
            )
            .unwrap();
        }
        Shape::LineString { vertices } => {
            write!(
                out,
                "<gml:LineString gml:id=\"g.{id}\" srsName=\"{SRS_NAME}\"><gml:posList srsDimension=\"2\">"
            )
            .unwrap();
            let (mut e, mut n) = (e, n);
            for v in 0..vertices.max(2) {
                if v > 0 {
                    out.push(' ');
                }
                write!(out, "{n:.2} {e:.2}").unwrap();
                e += rng.range(-20.0, 20.0);
                n += rng.range(-20.0, 20.0);
            }
            out.push_str("</gml:posList></gml:LineString>");
        }
        Shape::Polygon { vertices, holes } => {
            write!(
                out,
                "<gml:Polygon gml:id=\"g.{id}\" srsName=\"{SRS_NAME}\">"
            )
            .unwrap();
            write_polygon_rings(out, rng, e, n, vertices, holes);
            out.push_str("</gml:Polygon>");
        }
        Shape::MultiSurface { parts, vertices } => {
            write!(
                out,
                "<gml:MultiSurface gml:id=\"g.{id}\" srsName=\"{SRS_NAME}\">"
            )
            .unwrap();
            for p in 0..parts.max(1) {
                write!(
                    out,
                    "<gml:surfaceMember><gml:Polygon gml:id=\"g.{id}.{p}\">"
                )
                .unwrap();
                let offset = p as f64 * 300.0;
                write_polygon_rings(out, rng, e + offset, n, vertices, 0);
                out.push_str("</gml:Polygon></gml:surfaceMember>");
            }
            out.push_str("</gml:MultiSurface>");
        }
        Shape::ArcPolygon => {
            let r = rng.range(5.0, 50.0);
            write!(
                out,
                "<gml:Polygon gml:id=\"g.{id}\" srsName=\"{SRS_NAME}\"><gml:exterior><gml:Ring>\
                 <gml:curveMember><gml:Curve gml:id=\"c.{id}\"><gml:segments><gml:ArcString>\
                 <gml:posList srsDimension=\"2\">\
                 {n:.2} {:.2} {:.2} {e:.2} {n:.2} {:.2} {:.2} {e:.2} {n:.2} {:.2}\
                 </gml:posList></gml:ArcString></gml:segments></gml:Curve></gml:curveMember>\
                 </gml:Ring></gml:exterior></gml:Polygon>",
                e + r,
                n + r,
                e - r,
                n - r,
                e + r,
            )
            .unwrap();
        }
    }
}

/// An exterior ring around (`e`, `n`) and `holes` interior rings inside it.
fn write_polygon_rings(
    out: &mut String,
    rng: &mut Rng,
    e: f64,
    n: f64,
    vertices: usize,
    holes: usize,
) {
    let radius = rng.range(50.0, 120.0);
    out.push_str("<gml:exterior><gml:LinearRing><gml:posList srsDimension=\"2\">");
    write_ring(out, rng, e, n, radius, vertices.max(3), false);
    out.push_str("</gml:posList></gml:LinearRing></gml:exterior>");
    for h in 0..holes {
        // Small rings on a circle half way out, clockwise.
        let angle = h as f64 / holes as f64 * std::f64::consts::TAU;
        let (he, hn) = (
            e + radius * 0.5 * angle.cos(),
            n + radius * 0.5 * angle.sin(),
        );
        out.push_str("<gml:interior><gml:LinearRing><gml:posList srsDimension=\"2\">");
        write_ring(out, rng, he, hn, radius * 0.1, 8, true);
        out.push_str("</gml:posList></gml:LinearRing></gml:interior>");
    }
}

/// A closed ring of `vertices` positions plus the closing one, jittered
/// around a circle.
fn write_ring(
    out: &mut String,
    rng: &mut Rng,
    e: f64,
    n: f64,
    radius: f64,
    vertices: usize,
    clockwise: bool,
) {
    let mut first = None;
    for v in 0..vertices {
        let mut angle = v as f64 / vertices as f64 * std::f64::consts::TAU;
        if clockwise {
            angle = -angle;
        }
        let r = radius * rng.range(0.9, 1.0);
        let text = format!("{:.2} {:.2}", n + r * angle.sin(), e + r * angle.cos());
        if v > 0 {
            out.push(' ');
        }
        out.push_str(&text);
        first.get_or_insert(text);
    }
    out.push(' ');
    out.push_str(&first.expect("at least three vertices"));
}

/// SplitMix64: small, fast and the same on every platform.
struct Rng(u64);

impl Rng {
    fn new(seed: u64) -> Self {
        Rng(seed)
    }

    fn next(&mut self) -> u64 {
        self.0 = self.0.wrapping_add(0x9e37_79b9_7f4a_7c15);
        let mut z = self.0;
        z = (z ^ (z >> 30)).wrapping_mul(0xbf58_476d_1ce4_e5b9);
        z = (z ^ (z >> 27)).wrapping_mul(0x94d0_49bb_1331_11eb);
        z ^ (z >> 31)
    }

    /// Uniform in `0..bound`.
    fn below(&mut self, bound: u64) -> u64 {
        self.next() % bound
    }

    /// Uniform in `lo..hi`.
    fn range(&mut self, lo: f64, hi: f64) -> f64 {
        let unit = (self.next() >> 11) as f64 / (1u64 << 53) as f64;
        lo + unit * (hi - lo)
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn the_same_description_gives_the_same_bytes() {
        let synth = Synth::new(
            50,
            Shape::Polygon {
                vertices: 16,
                holes: 1,
            },
        );
        assert_eq!(synth.document(), synth.document());
        let other = Synth {
            seed: 1,
            ..synth.clone()
        };
        assert_ne!(synth.document(), other.document());
    }

    #[test]
    fn other_layer_features_are_interleaved() {
        let synth = Synth {
            other_layer_every: Some(4),
            ..Synth::new(20, Shape::Point)
        };
        let doc = synth.document();
        assert_eq!(doc.matches("<app:Building ").count(), 20);
        assert_eq!(doc.matches("<app:Road ").count(), 5);
    }

    #[test]
    fn rings_are_closed() {
        let snippet = Shape::Polygon {
            vertices: 5,
            holes: 2,
        }
        .snippet(3);
        for list in snippet.split("<gml:posList srsDimension=\"2\">").skip(1) {
            let list = list.split("</gml:posList>").next().unwrap();
            let numbers: Vec<&str> = list.split(' ').collect();
            let n = numbers.len();
            assert_eq!(numbers[..2], numbers[n - 2..], "{list}");
        }
        assert_eq!(
            Shape::Polygon {
                vertices: 5,
                holes: 2
            }
            .positions(),
            6 + 18
        );
    }
}
