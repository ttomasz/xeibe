/// Coefficients for converting latitude `from` into latitude `to`
/// (PROJ's `pj_auxlat_coeffs`).
///
/// Panics for a pair the table doesn't hold; the pairs are fixed in code.
pub(crate) fn coeffs(n: f64, from: AuxLat, to: AuxLat) -> [f64; ORDER] {
    let k = NUMBER * to as usize + from as usize;
    let mut o = PTRS[k];
    assert!(o != PTRS[k + 1], "no series from {from:?} to {to:?}");
    let mut f = [0.0; ORDER];
    let (mut d, n2) = (n, n * n);
    let even = (from as usize) <= AuxLat::Rectifying as usize
        && (to as usize) <= AuxLat::Rectifying as usize;
    for (l, slot) in f.iter_mut().enumerate() {
        // Order of the polynomial: in n² for the even series, else in n.
        let m = if even {
            (ORDER - l - 1) / 2
        } else {
            ORDER - l - 1
        };
        let x = if even { n2 } else { n };
        *slot = d * polyval(x, &COEFFS[o..=o + m]);
        o += m + 1;
        d *= n;
    }
    f
}

/// Σ p\[i\] xⁱ by Horner's method.
pub(crate) fn polyval(x: f64, p: &[f64]) -> f64 {
    p.iter().rev().fold(0.0, |y, &c| y * x + c)
}

/// Σ F\[k\] sin((2k + 2) ζ) by Clenshaw summation, ζ given by its sine and
/// cosine.
pub(crate) fn clenshaw(szeta: f64, czeta: f64, f: &[f64]) -> f64 {
    let (mut u0, mut u1) = (0.0, 0.0);
    let x = 2.0 * (czeta - szeta) * (czeta + szeta); // 2 cos 2ζ
    for &c in f.iter().rev() {
        let t = x * u0 - u1 + c;
        u1 = u0;
        u0 = t;
    }
    2.0 * szeta * czeta * u0
}

/// Convert auxiliary latitude ζ with the coefficients from [`coeffs`].
pub(crate) fn convert(zeta: f64, f: &[f64]) -> f64 {
    convert_sc(zeta, zeta.sin(), zeta.cos(), f)
}

/// As [`convert`], with the sine and cosine of ζ already known.
pub(crate) fn convert_sc(zeta: f64, szeta: f64, czeta: f64, f: &[f64]) -> f64 {
    zeta + clenshaw(szeta, czeta, f)
}

/// Rectifying radius divided by a: the quarter meridian over π/2 · a.
pub(crate) fn rectifying_radius(n: f64) -> f64 {
    const COEFF_RAD: [f64; 4] = [1.0, 1.0 / 4.0, 1.0 / 64.0, 1.0 / 256.0];
    polyval(n * n, &COEFF_RAD) / (1.0 + n)
}
