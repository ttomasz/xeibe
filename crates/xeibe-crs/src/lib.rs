//! EPSG CRS facts and PROJJSON definitions, generated from the EPSG dataset.
//!
//! <div class="warning">
//!
//! **Experimental, not for production use.** This crate is AI-generated and
//! has not been thoroughly tested yet. Its interfaces are not stable and will
//! change in the near future, in breaking ways.
//!
//! </div>
//!
//! Two tables, with deliberately different shapes because they are used very
//! differently (plus [`alias`], EPSG's other names for its CRSs):
//!
//! * [`CRS`] holds the facts the axis-order decision needs ([`FirstAxis`],
//!   dimension, units, area of use). It is on the hot path, so it is a plain
//!   sorted `static` array: no decompression, no allocation, no lazy init.
//! * PROJJSON is needed once per geometry column, only when writing GeoArrow or
//!   GeoParquet metadata, and is far too big to hold uncompressed. It lives in
//!   a zstd-sharded blob that [`projjson`] decompresses one shard at a time.
//!   Each root CRS's areas of use and scopes are in it, as PROJ writes them.
//!
//! EPSG's coordinate operations ([`operations_json`]) and its remarks on CRSs
//! and operations ([`crs_remarks`], [`operation_remarks`]) are blobs of their
//! own, decompressed on first use; code that never asks for a remark doesn't
//! carry that data.
//!
//! Everything here is generated by `scripts/gen_crs_tables.py` from an official
//! EPSG release. The data is IOGP's, not ours: see `EPSG-NOTICE.md`.
//!
//! No PROJ, GDAL or network access is involved, at build time or at run time.

use std::collections::HashMap;
use std::sync::{Mutex, OnceLock};

// Generated data: bbox longitudes such as 3.14 are not π.
