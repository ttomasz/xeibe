/// Direction of a CRS's first axis, in the authority's own axis order.
///
/// This is what decides whether coordinates written in authority order need
/// swapping; see `docs/geometry.md`, "CRS and axis order".
#[derive(Debug, Clone, Copy, PartialEq, Eq, Hash)]
pub enum FirstAxis {
    /// Easting or longitude first: x/y as written.
    EastOrLon,
    /// Northing or latitude first: y/x, so authority order needs a swap.
    NorthOrLat,
    /// Westing, southing, geocentric, ordinal and the like. Swapping the first
    /// two ordinates does not normalise these, so they are reported, not fixed.
    Other,
}

/// What kind of CRS this is, as EPSG classifies it.
#[derive(Debug, Clone, Copy, PartialEq, Eq, Hash)]
pub enum CrsKind {
    Geographic2d,
    Geographic3d,
    Projected,
    Geocentric,
    Vertical,
    Compound,
    Engineering,
    Derived,
}

impl CrsKind {
    /// Geographic CRSs take coordinates in degrees, which the range check and
    /// the dimension rule both care about.
    pub fn is_geographic(self) -> bool {
        matches!(self, CrsKind::Geographic2d | CrsKind::Geographic3d)
    }
}

/// One CRS from the EPSG dataset.
#[derive(Debug, Clone, PartialEq)]
pub struct CrsRecord {
    pub code: u32,
    /// EPSG's name, e.g. `"ETRS89 / PL-1992"`. Names change between EPSG
    /// releases; never match on this.
    pub name: &'static str,
    pub kind: CrsKind,
    pub first_axis: FirstAxis,
    /// Number of axes. A compound CRS reports horizontal plus vertical.
    pub dimension: u8,
    /// Size of the first axis's unit in metres, for CRSs measured in length
    /// (1.0 for metre, 0.3048… for foot). Used for `ArcByCenterPoint` radii.
    pub linear_unit_m: Option<f64>,
    /// Size of the first axis's unit in radians, for CRSs measured in angle.
    /// Distinguishes a CRS in gradians from one in degrees.
    pub angular_unit_rad: Option<f64>,
    /// EPSG's published area of use, in WGS 84 degrees, as
    /// `[south, west, north, east]`.
    ///
    /// This is EPSG's own bounding box, reproduced verbatim. It is deliberately
    /// *not* reprojected into the CRS's own units or axis order: doing that
    /// needs a projection engine, and the result would be our number rather
    /// than EPSG's. Callers that want it in axis order should use
    /// [`CrsRecord::area_in_axis_order`].
    pub area_wgs84: Option<[f32; 4]>,
    /// EPSG has retired this code. It is still resolvable, because real data
    /// keeps using retired codes for years.
    pub deprecated: bool,
}

impl CrsRecord {
    /// The area of use with its two horizontal bounds put in this CRS's own
    /// axis order, as `[min_first, min_second, max_first, max_second]`.
    ///
    /// Only meaningful for geographic CRSs, where the area of use and the
    /// coordinates share a unit. Returns `None` otherwise, so the range check
    /// abstains rather than comparing degrees against metres.
    pub fn area_in_axis_order(&self) -> Option<[f32; 4]> {
        if !self.kind.is_geographic() {
            return None;
        }
        let [south, west, north, east] = self.area_wgs84?;
        match self.first_axis {
            FirstAxis::NorthOrLat => Some([south, west, north, east]),
            FirstAxis::EastOrLon => Some([west, south, east, north]),
            FirstAxis::Other => None,
        }
    }
}

/// Look one EPSG code up. Includes deprecated codes.
pub fn get(code: u32) -> Option<&'static CrsRecord> {
    CRS.binary_search_by_key(&code, |record| record.code)
        .ok()
        .map(|index| &CRS[index])
}

/// The EPSG code a CRS alias names, e.g. `PL-1992` → 2180. Case is ignored.
///
/// These are EPSG's own aliases (its abbreviations and former names, INSPIRE
/// and national identifiers), limited to those that name a single CRS. An
/// alias EPSG gives to several live CRSs (`PL-ETRF2000`) is not here.
pub fn alias(name: &str) -> Option<u32> {
    let name = name.trim().to_lowercase();
    let aliases = aliases::ALIASES;
    aliases
        .binary_search_by(|(alias, _)| (*alias).cmp(name.as_str()))
        .ok()
        .map(|index| aliases[index].1)
}

