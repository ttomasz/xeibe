/// One of a CRS's usages in EPSG: an area of use and a scope.
#[derive(Debug, Clone, Copy, PartialEq)]
pub struct Usage {
    /// What the CRS is for, e.g. "Topographic mapping (medium and small
    /// scale)."
    pub scope: Option<&'static str>,
    /// EPSG's description of the area, e.g. "Poland - onshore and offshore."
    pub area: Option<&'static str>,
    /// The area's box in WGS 84 degrees: south, west, north, east (east <
    /// west across the antimeridian).
    pub bbox: Option<[f64; 4]>,
}

/// `scripts/gen_crs_tables.py` writes this: a magic, the raw length, then one
/// zstd frame of the extents, the scopes, and each CRS's usages referring to
/// them (`pack_usages` there describes the layout).
static USAGES_BLOB: &[u8] = include_bytes!("../data/usages.bin");

/// Little-endian reads from a byte slice, in order.
struct Cursor {
    bytes: &'static [u8],
    at: usize,
}

impl Cursor {
    fn take(&mut self, n: usize) -> &'static [u8] {
        let out = &self.bytes[self.at..self.at + n];
        self.at += n;
        out
    }
    fn u16(&mut self) -> u16 {
        u16::from_le_bytes(self.take(2).try_into().unwrap())
    }
    fn u32(&mut self) -> u32 {
        u32::from_le_bytes(self.take(4).try_into().unwrap())
    }
    fn f64(&mut self) -> f64 {
        f64::from_le_bytes(self.take(8).try_into().unwrap())
    }
    fn text(&mut self) -> Option<&'static str> {
        let len = self.u16() as usize;
        let text = std::str::from_utf8(self.take(len)).expect("data/usages.bin holds UTF-8 texts");
        (!text.is_empty()).then_some(text)
    }
}

fn usage_table() -> &'static HashMap<u32, Vec<Usage>> {
    static TABLE: OnceLock<HashMap<u32, Vec<Usage>>> = OnceLock::new();
    TABLE.get_or_init(|| {
        assert_eq!(
            &USAGES_BLOB[..4],
            b"XUS1",
            "data/usages.bin is not a usages blob"
        );
        let raw_len = u32::from_le_bytes(USAGES_BLOB[4..8].try_into().unwrap()) as usize;
        let raw = zstd::bulk::decompress(&USAGES_BLOB[8..], raw_len)
            .expect("data/usages.bin is a valid zstd frame");
        let mut c = Cursor {
            bytes: raw.leak(),
            at: 0,
        };
        let extents: Vec<(Option<[f64; 4]>, Option<&'static str>)> = (0..c.u32())
            .map(|_| {
                let _code = c.u32();
                let bbox = [c.f64(), c.f64(), c.f64(), c.f64()];
                let bbox = bbox.iter().all(|v| v.is_finite()).then_some(bbox);
                (bbox, c.text())
            })
            .collect();
        let scopes: Vec<Option<&'static str>> = (0..c.u32())
            .map(|_| {
                let _code = c.u32();
                c.text()
            })
            .collect();
        let mut out: HashMap<u32, Vec<Usage>> = HashMap::new();
        for _ in 0..c.u32() {
            let (code, extent, scope) = (c.u32(), c.u16() as usize, c.u16() as usize);
            let (bbox, area) = extents.get(extent).copied().unwrap_or((None, None));
            out.entry(code).or_default().push(Usage {
                scope: scopes.get(scope).copied().flatten(),
                area,
                bbox,
            });
        }
        out
    })
}

/// A CRS's usages in EPSG's order: what [`projjson`] writes as `scope`,
/// `area` and `bbox` (one usage) or `usages` (several). Empty for codes
/// EPSG does not define.
pub fn usages(code: u32) -> &'static [Usage] {
    usage_table().get(&code).map_or(&[], Vec::as_slice)
}

/// A JSON string literal.
fn json_string(text: &str, out: &mut String) {
    out.push('"');
    for ch in text.chars() {
        match ch {
            '"' => out.push_str("\\\""),
            '\\' => out.push_str("\\\\"),
            c if (c as u32) < 0x20 => out.push_str(&format!("\\u{:04x}", c as u32)),
            c => out.push(c),
        }
    }
    out.push('"');
}

/// The members of one usage, each after a comma, as PROJ writes them.
fn usage_members(usage: &Usage, out: &mut String) {
    if let Some(scope) = usage.scope {
        out.push_str(",\"scope\":");
        json_string(scope, out);
    }
    if let Some(area) = usage.area {
        out.push_str(",\"area\":");
        json_string(area, out);
    }
    if let Some([south, west, north, east]) = usage.bbox {
        out.push_str(&format!(
            ",\"bbox\":{{\"south_latitude\":{south},\"west_longitude\":{west},\
             \"north_latitude\":{north},\"east_longitude\":{east}}}"
        ));
    }
}

/// One CRS's PROJJSON line with its usages added before its id, which the
/// generator writes last; its code is that id's.
fn with_usages(line: &str) -> String {
    let Some(id_at) = line.rfind(",\"id\":") else {
        return line.to_owned();
    };
    let code = line[id_at..]
        .rsplit("\"code\":")
        .next()
        .and_then(|tail| tail.trim_end_matches('}').parse::<u32>().ok());
    let found = code.map(usages).unwrap_or(&[]);
    if found.is_empty() {
        return line.to_owned();
    }
    let mut members = String::new();
    if let [one] = found {
        usage_members(one, &mut members);
    } else {
        members.push_str(",\"usages\":[");
        for (i, usage) in found.iter().enumerate() {
            let mut one = String::new();
            usage_members(usage, &mut one);
            if i > 0 {
                members.push(',');
            }
            members.push('{');
            members.push_str(one.trim_start_matches(','));
            members.push('}');
        }
        members.push(']');
    }
    let mut out = String::with_capacity(line.len() + members.len());
    out.push_str(&line[..id_at]);
    out.push_str(&members);
    out.push_str(&line[id_at..]);
    out
}
