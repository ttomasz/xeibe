#!/usr/bin/env -S uv run --script
# /// script
# requires-python = ">=3.11"
# dependencies = []
# ///
"""Generate `crates/xeibe-reproject/src/grid/catalog.rs` from PROJ's grid table.

EPSG names each grid-based operation's file as its producer published it
(`ntf_r93.gsb`, `conus.las`, …). The grids xeibe-reproject reads are PROJ-data's
GeoTIFF conversions of those files, served from `cdn.proj.org` under other
names (`fr_ign_ntf_r93.tif`, `us_noaa_conus.tif`). PROJ maps one to the other
in its `grid_alternatives` table (MIT), which also says when PROJ-data stores
a grid the other way round from EPSG's operation. This script copies that
table, from the PROJ source release the test oracle uses, into a Rust table.

    scripts/gen_grid_catalog.py

The PROJ release and its checksum are those of `scripts/build_proj_oracle.py`
(keep the two in step); the tarball is cached in `target/proj-oracle/build/`.
"""

from __future__ import annotations

import hashlib
import sqlite3
import sys
import tarfile
import urllib.request
from pathlib import Path

REPO = Path(__file__).resolve().parent.parent
OUT = REPO / "crates" / "xeibe-reproject" / "src" / "grid" / "catalog.rs"
CACHE = REPO / "target" / "proj-oracle" / "build"

PROJ_VERSION = "9.8.1"
PROJ_URL = f"https://download.osgeo.org/proj/proj-{PROJ_VERSION}.tar.gz"
PROJ_SHA256 = "af5b731c145c1d13c4e3b4eeb7d167e94e845e440f71e3496b4ed8dae0291960"

SQL_FILES = ("grid_alternatives.sql", "grid_alternatives_generated_noaa.sql")
CDN = "https://cdn.proj.org/"


def tarball() -> Path:
    CACHE.mkdir(parents=True, exist_ok=True)
    path = CACHE / f"proj-{PROJ_VERSION}.tar.gz"
    if not path.exists():
        print(f"downloading {PROJ_URL}")
        with urllib.request.urlopen(PROJ_URL) as response:
            path.write_bytes(response.read())
    digest = hashlib.sha256(path.read_bytes()).hexdigest()
    if digest != PROJ_SHA256:
        path.unlink()
        sys.exit(f"{path.name}: sha256 {digest}, expected {PROJ_SHA256}")
    return path


def load_rows(path: Path) -> list[sqlite3.Row]:
    db = sqlite3.connect(":memory:")
    db.row_factory = sqlite3.Row
    db.execute(
        "create table grid_alternatives(original_grid_name text primary key, proj_grid_name text, "
        "old_proj_grid_name text, proj_grid_format text, proj_method text, inverse_direction int, "
        "package_name text, url text, direct_download int, open_license int, directory text)"
    )
    with tarfile.open(path) as tar:
        for name in SQL_FILES:
            member = tar.extractfile(f"proj-{PROJ_VERSION}/data/sql/{name}")
            assert member is not None, name
            db.executescript(member.read().decode())
    return db.execute("select * from grid_alternatives order by original_grid_name").fetchall()


def rust_str(s: str) -> str:
    return '"' + s.replace("\\", "\\\\").replace('"', '\\"') + '"'


def main() -> int:
    rows = load_rows(tarball())
    lines = [
        "// @generated by scripts/gen_grid_catalog.py from PROJ "
        f"{PROJ_VERSION} data/sql/grid_alternatives*.sql (MIT, see PROJ-NOTICE.md).",
        "// Do not edit.",
        "",
        "use super::catalog_types::Entry;",
        "",
        "/// PROJ's `grid_alternatives`, sorted by EPSG file name.",
        "pub(crate) static ENTRIES: &[Entry] = &[",
    ]
    on_cdn = 0
    for r in rows:
        assert r["package_name"] is None, r["original_grid_name"]
        cdn = (r["url"] or "").startswith(CDN)
        if cdn:
            # PROJ's own constraint: a CDN URL is the file's name, openly licensed.
            assert r["url"] == CDN + r["proj_grid_name"] and r["open_license"] == 1, r["original_grid_name"]
            on_cdn += 1
        lines.append(
            "    Entry {"
            f" epsg: {rust_str(r['original_grid_name'])},"
            f" file: {rust_str(r['proj_grid_name'])},"
            f" inverse: {'true' if r['inverse_direction'] else 'false'},"
            f" cdn: {'true' if cdn else 'false'} }},"
        )
    lines.append("];")
    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text("\n".join(lines) + "\n")
    print(f"wrote {OUT.relative_to(REPO)}: {len(rows)} grids, {on_cdn} on {CDN}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
